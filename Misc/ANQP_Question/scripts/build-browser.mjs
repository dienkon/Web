import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

// Build a classic script using Node's standard library, without installing packages.
// Order follows the dependencies between the small, project-owned modules.
const files = ['questions.mjs', 'session.mjs', 'panels.mjs', 'effects.mjs', 'app.mjs'];

export async function browserBundle() {
  const parts = await Promise.all(files.map(async file => {
    const source = await readFile(new URL(`../src/${file}`, import.meta.url), 'utf8');
    const classic = source
      .replace(/^import\s+\{[^\n]*\}\s+from\s+'\.\/[^']+';\r?\n/gm, '')
      .replace(/^export (?=(?:const|function)\b)/gm, '');
    if (/^\s*(?:import|export)\s/m.test(classic)) {
      throw new Error(`Unsupported module syntax in ${file}; update the build script.`);
    }
    return `// Source: src/${file}\n${classic.trim()}`;
  }));
  return `// Generated by: node scripts/build-browser.mjs\n// Edit src/*.mjs, then rebuild this file.\n(function () {\n'use strict';\n\n${parts.join('\n\n')}\n})();\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  await writeFile(new URL('../src/browser.js', import.meta.url), await browserBundle(), 'utf8');
  console.log('Built src/browser.js (classic script; supports file:// and HTTP).');
}
