/**
 * Lấy danh sách câu hỏi theo cấp độ (Level 1 - 25)
 */
export function getJourneyQuestionsForLevel(level: number): JourneyQuestion[] {
  const filtered = JOURNEY_QUESTIONS_100.filter((q) => q.level === level);
  if (filtered.length > 0) return filtered;
  // Fallback nếu level vượt quá 25
  return JOURNEY_QUESTIONS_100.filter((q) => q.level === ((level - 1) % 25) + 1);
}
