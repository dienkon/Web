import { chromium } from '@playwright/test';
import { mkdirSync, writeFileSync, unlinkSync } from 'node:fs';
import assert from 'node:assert/strict';
const origin = process.env.LAB_AUDIT_ORIGIN ?? 'http://127.0.0.1:6773';
const output = 'artifacts/automatic-experiments'; mkdirSync(output, { recursive: true });
const browser = await chromium.launch({ headless: true, args: ['--use-angle=swiftshader', '--enable-webgl'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', e => errors.push(e.stack ?? e.message));
page.on('console', msg => { if (msg.type() === 'error' && /shader|webgl|THREE/i.test(msg.text())) errors.push(msg.text()); });
try {
  await page.goto(`${origin}/?vfx=1`, { waitUntil: 'domcontentloaded' });
  await page.getByRole('button', { name: 'Tự động làm thí nghiệm', exact: true }).click();
  await page.getByRole('textbox', { name: 'Tìm thí nghiệm tự động' }).waitFor();
  const before = await page.evaluate(async () => {
    const { useAppStore } = await import('/src/store/useAppStore.ts');
    useAppStore.setState({ isSimulationPaused: true });
    return JSON.stringify({ vessels: useAppStore.getState().vessels, burners: useAppStore.getState().burners });
  });
  await page.getByRole('button', { name: 'Cu + HNO3', exact: true }).first().click();
  const dialog = page.getByRole('dialog', { name: 'Rạp thí nghiệm tự động' }); await dialog.waitFor();
  assert.equal(await page.evaluate(() => !!document.fullscreenElement), true);
  assert.equal(await page.evaluate(() => document.getElementById('root').inert), true);
  await page.getByRole('combobox', { name: 'Tốc độ tự động' }).selectOption('4');
  await page.waitForFunction(() => {
    const scene = document.querySelector('[data-auto-clouds]');
    return Number(scene?.getAttribute('data-auto-clouds')) > 35;
  }, null, { timeout: 90000 });
  await page.getByRole('button', { name: 'Tạm dừng tự động', exact: true }).click();
  const paused = await dialog.getAttribute('data-auto-elapsed');
  await page.getByRole('button', { name: 'Góc cận cảnh' }).click();
  await page.waitForTimeout(1200);
  assert.equal(await dialog.getAttribute('data-auto-elapsed'), paused);
  writeFileSync(`${output}/reload-probe.json`, '{"auditOutput":true}\n');
  await page.waitForTimeout(600);
  assert.equal(await dialog.count(), 1, 'Writing an audit report must not reload the active scene');
  unlinkSync(`${output}/reload-probe.json`);
  await page.screenshot({ path: `${output}/no2-close.png` });
  await page.getByRole('button', { name: 'Làm lại thí nghiệm' }).click();
  await page.waitForFunction(() => Number(document.querySelector('[data-auto-elapsed]')?.getAttribute('data-auto-elapsed')) < 5);
  await page.getByRole('button', { name: 'Góc toàn cảnh' }).click();
  await page.getByRole('button', { name: 'Tự xoay camera' }).click();
  await page.getByRole('button', { name: 'Thí nghiệm tiếp theo' }).click();
  await page.waitForFunction(() => document.querySelector('[data-auto-program]')?.getAttribute('data-auto-program') !== 'cu_hno3_conc');
  await page.getByRole('button', { name: 'Thoát thí nghiệm tự động' }).click();
  await dialog.waitFor({ state: 'detached' });
  assert.equal(await page.evaluate(() => !!document.fullscreenElement), false);
  const restored = await page.evaluate(async () => {
    const { useAppStore } = await import('/src/store/useAppStore.ts');
    return { snapshot: JSON.stringify({ vessels: useAppStore.getState().vessels, burners: useAppStore.getState().burners }), paused: useAppStore.getState().isSimulationPaused };
  });
  assert.equal(restored.snapshot, before); assert.equal(restored.paused, true);
  assert.equal(await page.evaluate(() => document.getElementById('root').inert), false);
  await page.getByRole('button', { name: 'NH3 + HCl', exact: true }).first().click();
  await dialog.waitFor();
  await page.getByRole('combobox', { name: 'Tốc độ tự động' }).selectOption('4');
  await page.waitForFunction(() => Number(document.querySelector('[data-auto-clouds]')?.getAttribute('data-auto-clouds')) > 20, null, { timeout: 90000 });
  await page.getByRole('button', { name: 'Tạm dừng tự động', exact: true }).click();
  await page.screenshot({ path: `${output}/nh4cl-smoke.png` });
  await page.getByRole('button', { name: 'Thoát thí nghiệm tự động' }).click();
  await dialog.waitFor({ state: 'detached' });
  await page.getByRole('textbox', { name: 'Tìm thí nghiệm tự động' }).fill('HCl + NaOH');
  await page.getByRole('button', { name: /^HCl \+ NaOH/ }).first().click();
  await dialog.waitFor();
  await page.getByRole('combobox', { name: 'Tốc độ tự động' }).selectOption('4');
  await page.getByRole('checkbox', { name: 'Liên tục' }).check();
  await page.waitForFunction(() => {
    const scene = document.querySelector('[data-auto-program]');
    return !!scene && scene.getAttribute('data-auto-program') !== 'hcl_naoh';
  }, null, { timeout: 90000 });
  await page.getByRole('button', { name: 'Thoát thí nghiệm tự động' }).click();
  await dialog.waitFor({ state: 'detached' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Cu + HNO3', exact: true }).first().click();
  await dialog.waitFor(); await page.screenshot({ path: `${output}/mobile.png` });
  await page.keyboard.press('Escape'); await dialog.waitFor({ state: 'detached' });
  await page.evaluate(() => window.addEventListener('click', () => { void document.documentElement.requestFullscreen(); }, { capture: true, once: true }));
  await page.getByRole('button', { name: 'Tự động làm thí nghiệm', exact: true }).click();
  await page.waitForFunction(() => !!document.fullscreenElement);
  await page.getByRole('button', { name: 'Cu + HNO3', exact: true }).first().click();
  await dialog.waitFor();
  await page.getByRole('button', { name: 'Toàn màn hình', exact: true }).click();
  await page.getByRole('button', { name: 'Thoát thí nghiệm tự động' }).click();
  await dialog.waitFor({ state: 'detached' });
  assert.equal(await page.evaluate(() => !!document.fullscreenElement), true);
  await page.evaluate(() => document.exitFullscreen());
  assert.deepEqual(errors, []);
  const report = { fullscreen: true, existingFullscreenPreserved: true, auditWritesDoNotReload: true, smokeRendered: true, solidSmokeRendered: true, pausedClockFrozen: true, restart: true, next: true, playlist: true, workbenchUnchanged: true, backgroundInert: true, mobile: true, escape: true, errors };
  writeFileSync(`${output}/browser.json`, JSON.stringify(report, null, 2) + '\n'); console.log(report);
} catch (error) {
  await page.screenshot({ path: `${output}/failure.png` }).catch(() => {});
  console.error({ errors, text: (await page.locator('body').innerText().catch(() => '')).slice(-2500) }); throw error;
} finally { await browser.close(); }
