import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const origin = process.env.LAB_AUDIT_ORIGIN ?? 'http://127.0.0.1:6767';
const output = resolve(process.env.LAB_AUDIT_OUTPUT ?? 'artifacts/onboarding');
mkdirSync(output, { recursive: true });
const browser = await chromium.launch({ headless: true, args: ['--use-angle=swiftshader', '--enable-webgl', '--enable-unsafe-swiftshader'] });
const context = await browser.newContext({ viewport: { width: 1440, height: 960 } });
const page = await context.newPage();
page.setDefaultTimeout(60000);
const errors = [], checks = [];
page.on('pageerror', error => errors.push(error.message));
await page.addInitScript(() => performance.setResourceTimingBufferSize(5000));
const guide = page.getByRole('dialog');
const launch = () => page.getByRole('button', { name: 'Mở hướng dẫn người mới', exact: true }).click();
const topic = name => guide.getByRole('navigation').getByRole('button', { name: new RegExp(name) }).click();

try {
  await page.goto(origin, { waitUntil: 'domcontentloaded' });
  await guide.waitFor();
  assert.equal(await guide.evaluate(el => el.matches(':modal')), true);
  assert.equal(await page.locator('#lab-guide-title').textContent(), 'Làm quen với phòng thí nghiệm');
  await page.screenshot({ path: `${output}/desktop-welcome.png` });
  checks.push('First visit opens a native modal with introduction');
  await guide.getByRole('button', { name: 'Switch guide to English' }).click();
  assert.equal(await page.locator('#lab-guide-title').textContent(), 'Meet your virtual lab');
  await guide.getByRole('button', { name: 'Chuyển hướng dẫn sang tiếng Việt' }).click();
  checks.push('Vietnamese and English content switches in place');
  await topic('Thêm và chọn dụng cụ');
  await guide.getByRole('button', { name: 'Thử mở kho dụng cụ' }).click();
  await page.getByRole('button', { name: 'Cốc mỏ 100mL', exact: false }).waitFor();
  await page.locator('#manual-lab canvas').waitFor();
  await page.evaluate(async () => {
    const url = performance.getEntriesByType('resource').map(e => e.name).findLast(n => /\/src\/store\/useAppStore\.ts(?:\?|$)/.test(n));
    window.__guideStore = (await import(url)).useAppStore;
  });
  const beforeAdd = await page.evaluate(() => window.__guideStore.getState().vesselIds.length);
  await page.getByRole('button', { name: 'Cốc mỏ 100mL', exact: false }).click();
  assert.equal(await page.evaluate(() => window.__guideStore.getState().vesselIds.length), beforeAdd + 1);
  await page.evaluate(() => {
    const state = window.__guideStore.getState();
    state.setSelectedVesselId(state.vesselIds.at(-1));
    window.__guideSelected = state.vesselIds.at(-1);
    window.__guideSnapshot = () => {
      const s = window.__guideStore.getState(), v = s.vessels[window.__guideSelected];
      return { id: s.selectedVesselId, dragging: s.draggingVesselId, position: v.position, rotationY: v.rotationY };
    };
  });
  await launch();
  const beforeKeys = await page.evaluate(() => window.__guideSnapshot());
  await page.keyboard.press('r');
  await page.keyboard.press('g');
  await page.keyboard.press('?');
  assert.deepEqual(await page.evaluate(() => window.__guideSnapshot()), beforeKeys);
  assert.equal(await page.getByRole('heading', { name: 'Bảng điều khiển phòng lab', exact: true }).count(), 0);
  for (let i = 0; i < 22; i++) {
    await page.keyboard.press('Tab');
    assert.equal(await page.evaluate(() => !!document.activeElement?.closest('dialog')), true);
  }
  await page.keyboard.press('Escape');
  assert.equal(await guide.count(), 0);
  assert.equal(await page.evaluate(() => window.__guideStore.getState().selectedVesselId === window.__guideSelected), true);
  checks.push('Equipment action opens correct tab; modal traps focus and blocks lab shortcuts, including Escape side effects');
  await launch();
  await topic('Đong và thêm hóa chất');
  await page.screenshot({ path: `${output}/desktop-measuring.png` });
  await guide.getByRole('button', { name: 'Thử mở kho hóa chất' }).click();
  await page.getByPlaceholder('Tìm hóa chất...').fill('H2O');
  await page.locator('#lab-left-panel [draggable]').filter({ has: page.getByText('H2O', { exact: true }) }).first().click();
  await page.getByRole('button', { name: '10 mL', exact: true }).click();
  await page.getByRole('button', { name: 'Đong & Rót 10.00 mL', exact: true }).click();
  await page.waitForFunction(() => window.__guideStore.getState().vessels[window.__guideSelected].volume_ml > 9.9);
  checks.push('The documented first exercise adds 10 mL of water through the actual UI');
  await launch();
  assert.equal(await page.locator('#lab-guide-title').textContent(), 'Đong và thêm hóa chất');
  await guide.getByRole('button', { name: 'Để sau', exact: true }).click();
  await page.reload({ waitUntil: 'domcontentloaded' });
  await page.getByRole('button', { name: 'Mở hướng dẫn người mới' }).waitFor();
  assert.equal(await guide.count(), 0);
  await launch();
  assert.equal(await page.locator('#lab-guide-title').textContent(), 'Đong và thêm hóa chất');
  checks.push('Dismissal survives reload; relaunch resumes the saved step');
  await topic('Đọc thông tin');
  await guide.getByRole('button', { name: 'Thử mở bảng quan sát' }).click();
  await page.locator('#lab-right-panel').waitFor();
  await launch();
  await topic('Làm thí nghiệm theo bài học');
  await guide.getByRole('button', { name: 'Thử mở danh sách bài học' }).click();
  await page.getByText('Chương trình thí nghiệm chuẩn', { exact: true }).waitFor();
  checks.push('Observation and lesson actions open the intended panels');
  await launch();
  await topic('Xem một thí nghiệm tự động');
  await guide.getByRole('button', { name: 'Thử chế độ tự động', exact: true }).click();
  await page.getByRole('button', { name: 'Chọn phản ứng', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Chọn phản ứng', exact: true }).click();
  await page.getByRole('textbox', { name: 'Tìm thí nghiệm tự động' }).waitFor();
  await page.getByRole('button', { name: 'CuSO4 + NaOH', exact: true }).first().click();
  await page.getByTestId('auto-caption').waitFor();
  await launch();
  await topic('Thêm và chọn dụng cụ');
  await guide.getByRole('button', { name: 'Thử mở kho dụng cụ' }).click();
  await page.getByRole('button', { name: 'Cốc mỏ 100mL', exact: false }).waitFor();
  checks.push('Automatic demonstration runs; practice can return from auto to the correct manual catalog tab');
  await launch();
  await topic('Sẵn sàng tự khám phá');
  await guide.getByRole('button', { name: 'Hoàn tất hướng dẫn' }).click();
  await page.reload({ waitUntil: 'domcontentloaded' });
  await page.getByRole('button', { name: 'Mở hướng dẫn người mới' }).waitFor();
  assert.equal(await guide.count(), 0);
  await launch();
  assert.equal(await page.locator('#lab-guide-title').textContent(), 'Làm quen với phòng thí nghiệm');
  checks.push('Completed guide stays dismissed and can be replayed from the start');
  for (const size of [{ width: 390, height: 844 }, { width: 320, height: 568 }, { width: 844, height: 390 }]) {
    await page.setViewportSize(size);
    await topic('Sẵn sàng tự khám phá');
    const layout = await guide.evaluate(el => {
      const box = el.getBoundingClientRect(), footer = el.querySelector('footer').getBoundingClientRect();
      return { x: box.x, y: box.y, right: box.right, bottom: box.bottom, overflow: el.scrollWidth > el.clientWidth, footerBottom: footer.bottom };
    });
    assert.ok(layout.x >= 0 && layout.y >= 0 && layout.right <= size.width && layout.bottom <= size.height, JSON.stringify(layout));
    assert.equal(layout.overflow, false);
    assert.ok(layout.footerBottom <= size.height);
    await page.screenshot({ path: `${output}/guide-${size.width}x${size.height}.png` });
    await guide.getByRole('button', { name: 'Tạm đóng hướng dẫn' }).click();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `Navigation overflow at ${size.width}`);
    const nav = await page.locator('.lab-navigation').evaluate(el => el.scrollWidth <= el.clientWidth);
    assert.equal(nav, true, `Navigation buttons overflow at ${size.width}`);
    await launch();
  }
  checks.push('Guide and navigation fit phone, small-phone and landscape viewports');
  const unavailable = await browser.newContext({ viewport: { width: 390, height: 844 } });
  await unavailable.addInitScript(() => { Storage.prototype.getItem = () => { throw new Error('Storage unavailable'); }; Storage.prototype.setItem = () => { throw new Error('Storage unavailable'); }; });
  const fallback = await unavailable.newPage();
  await fallback.goto(origin);
  await fallback.getByRole('dialog').waitFor();
  await fallback.getByRole('button', { name: 'Tiếp theo', exact: true }).click();
  await fallback.getByRole('button', { name: 'Tạm đóng hướng dẫn' }).click();
  await fallback.getByRole('button', { name: 'Mở hướng dẫn người mới' }).click();
  assert.equal(await fallback.locator('#lab-guide-title').textContent(), 'Thêm và chọn dụng cụ');
  await unavailable.close();
  checks.push('Onboarding remains usable when browser storage is unavailable');
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ checks, errors }, null, 2));
  writeFileSync(`${output}/report.json`, JSON.stringify({ checks, errors }, null, 2));
} catch (error) {
  await page.screenshot({ path: `${output}/failure.png` }).catch(() => {});
  throw error;
} finally { await browser.close(); }
