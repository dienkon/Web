export const LESSON_SPECIES: ReadonlyMap<string, LessonSpecies> = new Map(
  seeds.map(seed => [seed.id, { ...seed, molarMass: lessonMolarMass(seed.formula) }]),
);

export function getLessonSpecies(id: string): LessonSpecies {
  const species = LESSON_SPECIES.get(id);
  if (!species) throw new Error(`Unknown lesson species: ${id}`);
  return species;
}

export function findLessonSpeciesByFormula(formula: string): LessonSpecies[] {
  return [...LESSON_SPECIES.values()].filter(species => species.formula === formula);
}

export function lessonSpeciesName(id: string): string {
  return LESSON_SPECIES.get(id)?.name_vi ?? id;
}
