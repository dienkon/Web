import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
const input=new URL('../../shared/elements.json',import.meta.url),output=new URL('../src/data/periodicBoard.ts',import.meta.url);
const rows=JSON.parse(readFileSync(input,'utf8')).map(({z,symbol,period,group})=>[z,symbol,period,group]);
if(rows.length!==118||new Set(rows.map(r=>r[0])).size!==118)throw Error('Expected 118 distinct elements');
writeFileSync(output,'// Generated by scripts/generate-periodic-board.mjs from shared/elements.json.\nexport const PERIODIC_BOARD_ELEMENTS: readonly (readonly [number,string,number,number])[] = '+JSON.stringify(rows)+';\n');
console.log(fileURLToPath(output));
